class DeepThinker:
    """العقل التاني — بيشتغل بعد القراءة الأولى للإجابة"""

    def __init__(self, kb, reader):
        self.kb, self.reader = kb, reader
        self.speller = SpellFixer(kb)
        # قاموس الجذور: كلمات كاملة من ٣ حروف في نصوص الدروس (من غير «ال» والواو بس — عشان مايدخلش كلمات مقصوصة)
        for L in kb.lessons.values():
            for t in L["texts"]:
                for w in words(t):
                    for p in ("وال", "بال", "فال", "لل", "ال"):
                        if w.startswith(p) and len(w) - len(p) >= 3:
                            w = w[len(p):]
                            break
                    if len(w) == 3 and not w.isdigit() and w not in STOPWORDS:
                        ROOT_LEXICON.add(w)
        _root_cache.clear()

    # ---------------- ١) فهم السؤال ----------------
    def analyze_question(self, q):
        text = q.get("q", "")
        ws = set(words(text))
        intents = [name for name, keys in _INTENT_W if ws & keys]
        need = None
        for w in words(text):
            if w in COUNT_WORDS:
                need = COUNT_WORDS[w]
                break
        sides = []
        m = re.search(r"بين\s+(.+?)\s+و(.+?)(?:\s+من حيث|\s+مع|[،,.؟?]|$)", normalize(text))
        if "compare" in intents and m:
            sides = [content_tokens(m.group(1)), content_tokens(m.group(2))]
        return {"intents": intents or ["explain"], "count": need, "sides": [s for s in sides if s]}

    def check_requirements(self, qa, answer, res, th):
        """الإجابة ماشية مع نوع السؤال؟ (دي بتطلع نصايح، والدرجة نفسها من الأفكار)"""
        tips = []
        names = "، ".join(INTENT_AR[i] for i in qa["intents"] if i in INTENT_AR)
        th.append("فهمت السؤال: مطلوب فيه %s." % names)
        ws = words(answer)
        partial = bool(res["missing"] or res["partial"])
        if ("cause" in qa["intents"] or "effect" in qa["intents"]) and partial:
            if not find_causal(ws) and not any(w in ("لان", "لانه", "لانها", "بسبب", "حيث") for w in ws):
                tips.append("السؤال عايز سبب أو نتيجة — اربط كلامك بكلمات زي «لأن» أو «أدى إلى».")
        if qa["sides"]:
            at = set(content_tokens(answer))
            miss = [s for s in qa["sides"] if self.reader.soft_recall(s, list(at), at) < 0.5]
            if len(miss) == 1:
                th.append("السؤال مقارنة بين حاجتين، والإجابة اتكلمت عن ناحية واحدة بس.")
                tips.append("المقارنة لازم تتكلم عن الناحيتين.")
            elif not miss:
                th.append("الإجابة اتكلمت عن ناحيتين المقارنة.")
        if "evidence" in qa["intents"] and len(content_tokens(answer)) <= 3:
            th.append("السؤال مطلوب فيه دليل، والإجابة من غير دليل.")
            tips.append("السؤال بيقول «مدللًا» — اكتب الدليل من النص بعد إجابتك.")
        if qa["count"]:
            items = [x for x in re.split(r"[،,.؛;\n]|\sو(?=\S)", answer) if len(content_tokens(x)) >= 1]
            if len(items) < qa["count"] and partial:
                tips.append("السؤال طالب %s نقاط على الأقل." % to_ar(qa["count"]))
        return tips

    # ---------------- ٢) قراءة تانية للأفكار الناقصة ----------------
    def prepared_tokens(self, answer):
        """كلام الطالب بعد: العامية ← فصحى ، والإملاء متصلح"""
        msa = colloquial_to_msa(answer, self.kb.vocab)
        tag = tagged_tokens(msa)
        fixed = [(self.speller.fix(t), n) for t, n in tag]
        return msa, fixed

    def root_recall(self, ptoks, pool):
        """نسبة كلمات الفكرة الموجودة في كلام الطالب (بالكلمة أو بالجذر)"""
        roots = {}
        for a in pool:
            roots.setdefault(arabic_root(a), a)
        num = den = 0.0
        hits = []
        for t in ptoks:
            w = self.kb.w(t)
            den += w
            if t in pool:
                num += w
                hits.append(t)
                continue
            m = max([self.reader.tok_sim(t, a) for a in pool] or [0.0])
            r = arabic_root(t)
            if len(r) >= 3 and r in roots:
                m = max(m, 0.9)
            if m >= 0.7:
                hits.append(t)
            num += w * (m if m >= 0.7 else 0.0)
        return (num / den if den else 0.0), hits

    def _tok_match(self, t, t_raw, a, a_raw):
        """قد إيه كلمة الفكرة شبه كلمة الطالب: بالكلمة، بالمرادف، أو بالجذر
        (الجذر بيتحسب من الكلمة الأصلية كمان — «لغوية» و«ولغويه» نفس الجذر حتى لو التجذيع قصّهم مختلف)"""
        if t == a:
            return 1.0
        m = self.reader.tok_sim(t, a)
        if m < 0.9:
            rt = {arabic_root(t), arabic_root(t_raw)}
            ra = {arabic_root(a), arabic_root(a_raw)}
            if any(len(r) >= 3 for r in rt & ra):
                m = max(m, 0.9)
        return m

    def polar_recall(self, p, fixed, msa=""):
        """نسبة كلمات الفكرة في كلام الطالب — مع احترام اتجاه الفكرة:
        لو الفكرة منفية («لا يرى النبوغ موهبة فطرية فقط» / «يصعب تفتيته») لازم الطالب ينفي هو كمان
        («مش موهبة ربانية وبس» / «محدش يقدر يفرقه») — حتى لو النفي جه في مكان تاني من الجملة.
        ولو الفكرة مثبتة والطالب نفاها، يبقى مفيش إنقاذ."""
        ptag = [(t, n) for t, n in tagged_tokens(p) if t]
        if not ptag or not fixed:
            return 0.0, []
        praw = {stem(w): w for w in words(p)}
        sraw = {stem(w): w for w in words(msa)}
        num = den = 0.0
        hits = []
        for t, n in ptag:
            w = self.kb.w(t)
            den += w
            best, bneg = 0.0, False
            for a, an in fixed:
                m = self._tok_match(t, praw.get(t, t), a, sraw.get(a, a))
                if m > best or (m == best and bneg and not an):  # لو اتساووا: المثبت أولى
                    best, bneg = m, an
            if best >= 0.7:
                num += w * best
                hits.append((t, bneg, w))
        self._last_polar = (ptag, hits)
        pneg = any(n for _, n in ptag)
        sneg = any(bn for _, bn, _ in hits)
        if pneg != sneg:
            return 0.0, []
        return (num / den if den else 0.0), [t for t, bn, _ in hits if not bn]

    def polarity_flip(self, p, fixed, msa, partial=False):
        """الطالب ذكر كلام الفكرة بس في الاتجاه العكسي؟
        فكرة مثبتة ونص كلماتها أو أكتر منفية عند الطالب — أو فكرة منفية والطالب مانفاش خالص — أو ضدها صريح
        partial: فكرة اتحسبت «جزئيًا» — لو كل الدليل عليها (ولو كلمة واحدة) منفي عند الطالب، يبقى الدليل ضدها مش معاها"""
        self.polar_recall(p, fixed, msa)
        ptag, hits = self._last_polar
        if partial and hits and all(bn for _, bn, _ in hits) and not any(n for _, n in ptag):
            return True
        if len(hits) < 2 and not self.reader.contradicts(ptag, fixed):
            return False
        pneg = any(n for _, n in ptag)
        wt = sum(w for _, _, w in hits) or 1.0
        wneg = sum(w for _, bn, w in hits if bn)
        if pneg:  # «عدم التأثر...»: بيتشال بس لو الطالب قال الفعل المنفي نفسه بالإيجاب («اتأثروا») ومنفاش حاجة
            head = next(t for t, n in ptag if n)
            return wneg == 0 and any(h == head and not bn for h, bn, _ in hits)
        return wneg / wt >= 0.5 or self.reader.contradicts(ptag, fixed)

    def polarity_review(self, answer, res, th):
        """مراجعة الاتجاه: بعد ما الكلام العامي اتحوّل فصحى — النفي العامي («محدش يقدر يكتسبها»، «مبقاش فيه وحدة»)
        ممكن القراءة الأولى تكون ماشافتهوش. فبنراجع كل فكرة اتحسبت: هل كلام الطالب فعلًا بيأكدها؟"""
        msa, fixed = self.prepared_tokens(answer)
        if normalize(msa) == normalize(answer):
            return 0  # الكلام فصحى — القراءة الأولى شافت النفي بنفسها
        pulled = 0
        for bucket in ("found", "partial"):
            for p in list(res[bucket]):
                if self.polarity_flip(p, fixed, msa, partial=(bucket == "partial")):
                    res[bucket].remove(p)
                    res["missing"].append(p)
                    th.append("مراجعة الاتجاه: فكرة «%s» — لما فهمت كلامك العامي لقيته بيقول عكسها أو بينفيها، فمش هتتحسب." % p)
                    pulled += 1
        return pulled

    def second_reading(self, q, answer, res, flagged_pts, info, th, flagged=None):
        if not (res["missing"] or res["partial"]) or info["known"] < 0.15 or info["novelty"] < 0.3:
            return 0
        msa, fixed = self.prepared_tokens(answer)
        pos = {t for t, n in fixed if not n}
        seq = fixed
        changed = [(t0, t1) for (t0, _), (t1, _) in zip(tagged_tokens(msa), fixed) if t0 != t1]
        if changed:
            th.append("قراءة تانية: صلّحت الإملاء في %s — %s." % (
                "كلمة" if len(changed) == 1 else "%s كلمات" % to_ar(len(changed)),
                "، ".join("«%s» ← «%s»" % c for c in changed[:3])))
        if normalize(msa) != normalize(answer):
            th.append("قراءة تانية: فهمت الكلام العامي بمعناه الفصيح.")
        rescued = 0
        # مراجعة «العكس»: القراءة الأولى ممكن تفهم جملة عامية بالعكس («محدش يقدر يفرقه» = مستحيل يتفرق = متحد)
        # فلو بعد تحويل الكلام للفصحى الجملة مابقتش بتعكس الفكرة، نشيل العلامة ونقيّمها من جديد
        if flagged is not None and normalize(msa) != normalize(answer):
            for k in range(len(flagged_pts) - 1, -1, -1):
                p = flagged_pts[k]
                ptag = tagged_tokens(p)
                if self.reader.contradicts(ptag, seq):
                    continue
                if self.polar_recall(p, fixed, msa)[0] < 0.3:  # لازم يكون فيه دليل إن الكلام بيأكد الفكرة
                    continue
                flagged_pts.pop(k)
                if k < len(flagged):
                    flagged.pop(k)
                th.append("مراجعة: فكرة «%s» — لما حوّلت كلامك العامي للفصحى لقيت إنه مش بيعكسها، فهقيّمها من جديد." % p)
        for p in list(res["missing"]) + list(res["partial"]):
            was_partial = p in res["partial"]
            if p in flagged_pts:
                continue
            if not content_tokens(p):
                continue
            rec, hits = self.polar_recall(p, fixed, msa)
            if rec < 0.5 or self.reader.contradicts(tagged_tokens(p), seq):
                continue
            if (was_partial and rec < 0.7):  # الجزئي متأكدين من نصه، فعتبة الترقية أقل شوية
                continue
            if was_partial:  # كانت متحسوبة نصها — الأدلة بالجذور كاملة فتترقّى
                res["partial"].remove(p)
                res["found"].append(p)
                th.append("فكرة «%s»: كنت حاسبها نص، وفي القراءة التانية لقيت كل كلماتها بجذورها — تتحسب كاملة." % p)
                rescued += 1
                continue
            res["missing"].remove(p)
            if rec >= 0.75:
                res["found"].append(p)
                th.append("فكرة «%s»: لقيتها في القراءة التانية (بجذور الكلمات أو بعد تصليح الإملاء)." % p)
            else:
                res["partial"].append(p)
                th.append("فكرة «%s»: لقيت جزء منها في القراءة التانية." % p)
            rescued += 1
        return rescued

    # ---------------- ٣) الاستجواب: نسبة كل معلومة لصاحبها ----------------
    def binding_units(self, q, points):
        """بيطلّع «صاحب» كل فكرة ومعلوماتها: (الحجج العقلية ← الأرقام والإحصائيات)"""
        lines = [ln.strip().rstrip(".") for ln in q.get("model", "").split("\n") if ln.strip()]
        units = []
        if len(lines) >= 2 and all(":" in ln and len(content_tokens(ln.split(":", 1)[0])) <= 4 for ln in lines):
            for ln in lines:  # إجابة نموذجية على شكل «المصطلح: معناه»
                h, b = ln.split(":", 1)
                units.append({"head_text": h.strip(), "head": content_tokens(h), "body": content_tokens(b), "point": None})
        else:
            prev = None
            for p in points:
                toks = content_tokens(p)
                if not toks:
                    continue
                first = words(p)[0] if words(p) else ""
                ref = prev is not None and (first in REF_WORDS or (len(first) >= 5 and first.endswith(("ها", "هما", "هم"))))
                units.append({"point": p, "toks": toks, "ref": ref})
                prev = p
            if len(units) < 2:
                return []
            count = Counter(t for u in units for t in set(u["toks"]))
            for k, u in enumerate(units):
                if u["ref"]:
                    base = units[k - 1]
                    u["head"], u["head_text"] = base.get("head", []), base.get("head_text", "")
                    u["body"] = [t for t in u["toks"] if count[t] == 1]
                else:
                    cand = [t for t in u["toks"][:2] if count[t] == 1]
                    if not cand:
                        u["head"] = []
                        continue
                    h = cand[0]
                    u["head"] = [h]
                    orig = [w for w in words(u["point"]) if stem(w) == h]
                    u["head_text"] = orig[0] if orig else h
                    u["body"] = [t for t in u["toks"] if count[t] == 1 and t != h]
        units = [u for u in units if u.get("head") and u.get("body")]
        heads = {tuple(u["head"]) for u in units}
        if len(heads) < 2:
            return []
        # كل كلمة من المعلومات لازم تكون مميزة لصاحبها (مش موجودة عند صاحب تاني)
        owner = {}
        for u in units:
            for t in u["body"]:
                owner.setdefault(t, set()).add(tuple(u["head"]))
        for u in units:
            u["body"] = [t for t in u["body"] if len(owner[t]) == 1 and t not in {x for hh in heads for x in hh}]
        return [u for u in units if u["body"]]

    def check_binding(self, q, answer, res, th, qa):
        units = self.binding_units(q, res["found"] + res["partial"] + res["missing"])
        if not units:
            return []
        is_pairing = "compare" in qa["intents"] or any(u.get("ref") for u in units) or \
            any(u["point"] is None for u in units) or re.search(r"\bمثل\b|امثلته|امثلتها|وسائل", normalize(q.get("model", "")))
        if not is_pairing:
            return []
        heads = []
        for u in units:
            if tuple(u["head"]) not in [tuple(h) for h, _ in heads]:
                heads.append((u["head"], u["head_text"]))
        events = []
        for a in content_tokens(answer):
            hk = next((tuple(h) for h, _ in heads if any(a == t or dice(a, t) >= 0.75 for t in h)), None)
            if hk:
                events.append(("h", hk))
                continue
            for k, u in enumerate(units):
                if any(a == t or dice(a, t) >= 0.7 for t in u["body"]):
                    events.append(("b", k))
                    break
        if not events:
            return []
        # الطالب بيكتب «الصاحب ← معلوماته» ولا «المعلومات ← صاحبها»؟
        first_h = next(i for i, e in enumerate(events) if e[0] == "h") if any(e[0] == "h" for e in events) else len(events)
        n_b = sum(1 for e in events if e[0] == "b")
        head_first = events[0][0] == "h" or (n_b and sum(1 for e in events[:first_h] if e[0] == "b") / n_b < 0.34)
        present_heads = {v for kind, v in events if kind == "h"}
        given = {}
        for i, (kind, v) in enumerate(events):
            if kind != "b":
                continue
            rng = range(i - 1, -1, -1) if head_first else range(i + 1, len(events))
            h = next((events[j][1] for j in rng if events[j][0] == "h"), None)
            if h:
                given.setdefault(v, set()).add(h)
        name = {tuple(h): t for h, t in heads}
        bad = []
        for k, u in enumerate(units):
            own = tuple(u["head"])
            if own not in present_heads or k not in given or own in given[k]:
                continue
            wrong_to = sorted(given[k], key=lambda h: name.get(h, ""))[0]
            bad.append((u, wrong_to))
        notes = []
        for u, wrong_to in bad:
            credited = [u["point"]] if u["point"] and (u["point"] in res["found"] or u["point"] in res["partial"]) else []
            if u["point"] and not credited:
                continue  # الفكرة أصلًا مش محسوبة، فمفيش حاجة تتسحب
            label = u["point"] or ("%s: ..." % u["head_text"])
            th.append("استجواب: معلومة «%s» اتنسبت في كلامك لـ«%s»، وهي في الدرس تبع «%s» — فمش هتتحسب."
                      % (self.short_body(u), name.get(wrong_to, ""), u["head_text"]))
            affected = [u["point"]] if u["point"] else [p for p in res["found"] + res["partial"]
                                                         if self.reader.soft_recall(content_tokens(p), u["body"]) >= 0.5]
            for p in affected:
                for lst in ("found", "partial"):
                    if p in res[lst]:
                        res[lst].remove(p)
                        res["missing"].append(p)
            notes.append("راجع: «%s» تبع «%s» مش «%s»." % (self.short_body(u), u["head_text"], name.get(wrong_to, "")))
            res.setdefault("bound_wrong", []).append(label)
        return notes

    def short_body(self, u):
        src = u["point"] or ""
        if src:
            ws = [w for w in words(src) if stem(w) in u["body"]]
            if ws:
                return " ".join(ws[:4])
        return " ".join(u["body"][:3])

    # ---------------- ٣) الاستجواب: السبب والنتيجة ----------------
    def check_causality(self, q, answer, res, th):
        rels = []
        for s in split_sentences(q.get("model", "")):
            ce = split_cause_effect(s)
            if ce:
                rels.append(ce)
        if not rels:
            return []
        notes = []
        for s in split_sentences(answer):
            ce = split_cause_effect(s)
            if not ce:
                continue
            ac, ae = ce
            for mc, me in rels:
                right = self.reader.soft_recall(mc, ac) + self.reader.soft_recall(me, ae)
                flip = self.reader.soft_recall(mc, ae) + self.reader.soft_recall(me, ac)
                if flip >= 1.2 and flip - right >= 0.5:
                    th.append("استجواب: في جملة «%s» السبب والنتيجة معكوسين — الدرس بيقول إن «%s» هو السبب."
                              % (Thinker.short(s, 70), " ".join(mc[:4])))
                    for p in list(res["found"]):
                        pt = content_tokens(p)
                        if self.reader.soft_recall(pt, mc + me) >= 0.6:
                            res["found"].remove(p)
                            res["partial"].append(p)
                    notes.append("السبب والنتيجة معكوسين في كلامك — راجع مين أدى لمين.")
                    res["causal_flip"] = True
                    break
        return notes[:1]

    # ---------------- ٣) الاستجواب: الأرقام ----------------
    def check_numbers(self, res, info, th):
        notes = []
        for (sc, where, flag), p in zip(info["pscores"], info["points"]):
            pn = numbers_plus(p)
            if not pn or not where or (p not in res["found"] and p not in res["partial"]):
                continue
            wn = numbers_plus(where)
            if wn and not (pn & wn):
                th.append("استجواب: فكرة «%s» — كتبت الرقم %s، والدرس بيقول %s." % (
                    p, "، ".join(to_ar(x) for x in sorted(wn)), "، ".join(to_ar(x) for x in sorted(pn))))
                if p in res["found"]:
                    res["found"].remove(p)
                    res["partial"].append(p)
                else:
                    res["partial"].remove(p)
                    res["missing"].append(p)
                notes.append("راجع الأرقام: «%s»." % p)
        return notes

    # ---------------- ٣) الاستجواب: الإجابة بتقول الحاجة وعكسها؟ ----------------
    def check_self_consistency(self, answer, res, th):
        """طالب كتب «الحكومة المركزية قوية» وبعدها «الحكومة المركزية ضعيفة» عشان يلحق الدرجة:
        الفكرة اتقالت واتقال عكسها، فمش هتتحسب"""
        sents = [s for s in split_sentences(answer) if content_tokens(s)]
        clauses = [c for s in sents for c in re.split(r"[،,]|\sلكن\s|\sبينما\s", s) if content_tokens(c)]
        if len(clauses) < 2:
            return []
        notes = []
        for p in list(res["found"]) + list(res["partial"]):
            ptag = tagged_tokens(p)
            ptoks = [t for t, _ in ptag]
            support = contra = None
            for c in clauses:
                ct = content_tokens(c)
                if self.reader.soft_recall(ptoks, ct) < 0.5:
                    continue
                ctag = tagged_tokens(c)
                pos = {t for t, n in ctag if not n}
                neg = {t for t, n in ctag if n}
                if self.reader.contradicts(ptag, ctag) or (self.reader.polar_recall(ptag, pos, neg) < 0.35):
                    contra = contra or c
                else:
                    support = support or c
            if support and contra:
                th.append("استجواب: فكرة «%s» اتقالت في «%s» واتقال عكسها في «%s» — الإجابة متناقضة فمش هتتحسب."
                          % (p, Thinker.short(support, 50), Thinker.short(contra, 50)))
                for lst in ("found", "partial"):
                    if p in res[lst]:
                        res[lst].remove(p)
                res["missing"].append(p)
                notes.append("إجابتك قالت الفكرة وعكسها — اختار رأي واحد واكتبه.")
        return notes[:1]

    # ---------------- ٣) الاستجواب: الفكرة محسوبة من كلام السؤال بس؟ ----------------
    def check_echo(self, q, answer, res, th):
        """لو الفكرة كلماتها كلها موجودة في السؤال، والطالب مكتبش أي حاجة زيادة عليها من عنده،
        يبقى هو بس ردّد كلام السؤال — فبتتحسب نص فكرة مش فكرة كاملة"""
        qt = set(content_tokens(q.get("q", "")))
        if not qt:
            return []
        at = content_tokens(answer)
        own = [t for t in at if t not in qt]
        demoted = []
        for p in list(res["found"]):
            pt = content_tokens(p)
            if len(pt) < 2 or sum(1 for t in pt if t in qt) / len(pt) < 0.8:
                continue
            if len(own) < max(2, len(pt)):  # مفيش كلام من عنده غير كلام السؤال
                res["found"].remove(p)
                res["partial"].append(p)
                demoted.append(p)
        if demoted:
            th.append("استجواب: %s كلامها موجود في السؤال نفسه، والإجابة مزادتش عليه شرح — فاتحسبت نص فكرة."
                      % "، ".join("«%s»" % p for p in demoted))
            return ["اشرح بكلامك، متكررش كلام السؤال بس."]
        return []

    # ---------------- ٣) الاستجواب: حشو الدرس كله ----------------
    def check_padding(self, q, answer, info, res, th):
        """طالب نسخ فقرات كتير من الدرس (مش إجابة السؤال) عشان يلقط الأفكار صدفة:
        الإجابة طويلة جدًا، وأغلب جملها مالهاش علاقة بأفكار السؤال"""
        mt = content_tokens(q.get("model", ""))
        at = info["tokens"]
        if len(at) < max(30, 3 * len(mt)):
            return None
        pts = [content_tokens(p) for p in info["points"]]
        sents = [content_tokens(s) for s in split_sentences(answer)]
        sents = [x for x in sents if len(x) >= 3]
        if len(sents) < 4:
            return None
        useful = sum(1 for x in sents if max([self.reader.soft_recall(p, x) for p in pts] or [0]) >= 0.4)
        prec = useful / len(sents)
        th.append("استجواب: الإجابة %s جملة، منها %s بس ليها علاقة بالمطلوب." % (to_ar(len(sents)), to_ar(useful)))
        if prec < 0.3:
            return (0.5, "الإجابة طويلة جدًا وأغلبها كلام من الدرس مالوش علاقة بالسؤال — اكتب المطلوب بس.")
        return None

    def hedging(self, answer, th):
        n = sum(1 for w in words(answer) if w in HEDGE_WORDS)
        if n >= 2:
            th.append("ملاحظة: الإجابة فيها تردد («ربما / ممكن / أعتقد») — دققت فيها أكتر.")
        return n

    # ---------------- ٤) المداولة بين المحكّمين ----------------
    def deliberate(self, ratio, frac, p_nn, f, caps, res, th, downgraded):
        judges = [("الأفكار", frac), ("الشبكة العصبية", p_nn), ("القرب في المعنى", f[4]), ("الارتباط بالدرس", f[5])]
        th.append("مداولة: " + " — ".join("%s %s٪" % (n, to_ar(round(v * 100))) for n, v in judges))
        spread = max(frac, p_nn, f[4]) - min(frac, p_nn, f[4])
        out = ratio
        if not caps and frac < 1.0:
            ceil = frac + (0.05 if downgraded else 0.3)  # الاستجواب سحب أفكار: الدرجة على قد الأفكار الباقية
            if out > ceil + 1e-9:
                th.append("مداولة: الشبكة شايفة الإجابة أحسن من الأفكار اللي فيها فعلًا، فالدرجة متزيدش عن اللي الأفكار تستاهله.")
                out = ceil
        lower = spread >= 0.5
        if lower:
            th.append("مداولة: المحكّمين مختلفين في رأيهم، فالثقة في الدرجة أقل.")
        return out, lower

    # ---------------- ٥) خلاصة التفكير ----------------
    def conclusion(self, res, marks, score):
        f, p, m = len(res["found"]), len(res["partial"]), len(res["missing"])
        total = f + p + m
        bits = ["لقيت %s من %s أفكار كاملة" % (to_ar(f), to_ar(total))]
        if p:
            bits.append("و%s ناقصها تفاصيل" % to_ar(p))
        if res.get("bound_wrong"):
            bits.append("وفي معلومات منسوبة لغير صاحبها")
        if res.get("causal_flip"):
            bits.append("والسبب والنتيجة معكوسين")
        return "خلاصة التفكير: " + "، ".join(bits) + " — فالدرجة %s من %s." % (to_ar(score), to_ar(marks))


