def _lex_parse(src):
    """بيقرا القاموس سطر سطر ويرجّع: المرادفات، الأضداد، الجمل العامية"""
    groups, pairs, phrases, entries = [], [], {}, []
    for line in src.strip().splitlines():
        f = [x.strip() for x in line.split("|")] + ["", "", "", ""]
        side_a, side_b = f[0].split(), f[1].split()
        col_a = [c.strip() for c in f[2].split("،") if c.strip()]
        col_b = [c.strip() for c in f[3].split("،") if c.strip()]
        entries.append((side_a, side_b, col_a, col_b))
        for side, col in ((side_a, col_a), (side_b, col_b)):
            if not side:
                continue
            singles = [c for c in col if " " not in c]
            groups.append(side + singles)
            for c in col:
                if " " in c:  # جملة عامية ← أول كلمة في ناحيتها
                    phrases[tuple(normalize(c).split())] = normalize(side[0])
        if side_a and side_b:
            pairs.append((side_a + [c for c in col_a if " " not in c], side_b + [c for c in col_b if " " not in c]))
    return groups, pairs, phrases, entries


def _lex_ok(w):
    """كلمة بعد التجذيع بتبقى كلمة شائعة («قبل» «بين» «كل») أو حرفين ملهمش معنى («آلام» ← «ام») تتشال"""
    x = normalize(w)
    st = stem(x)
    return st not in STOPWORDS and (len(st) >= 3 or (len(st) == 2 and st == x))


