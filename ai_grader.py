class JSLiteralParser:
    ID_RE = re.compile(r"[A-Za-z_$][\w$]*")
    NUM_RE = re.compile(r"-?\d+(?:\.\d+)?")

    def __init__(self, text, pos=0):
        self.s, self.i, self.n = text, pos, len(text)

    def error(self, msg):
        line = self.s.count("\n", 0, self.i) + 1
        raise ValueError("خطأ في قراءة script.js (سطر %d): %s" % (line, msg))

    def ws(self):
        s = self.s
        while self.i < self.n:
            c = s[self.i]
            if c in " \t\r\n\ufeff":
                self.i += 1
            elif s.startswith("//", self.i):
                j = s.find("\n", self.i)
                self.i = self.n if j < 0 else j + 1
            elif s.startswith("/" + "*", self.i):
                j = s.find("*" + "/", self.i + 2)
                self.i = self.n if j < 0 else j + 2
            else:
                break

    def peek(self):
        self.ws()
        if self.i >= self.n:
            self.error("الملف خلص فجأة")
        return self.s[self.i]

    def value(self):
        c = self.peek()
        if c == "[":
            return self.array()
        if c == "{":
            return self.obj()
        if c in "\"'":
            return self.string()
        if c == "-" or c.isdigit():
            m = self.NUM_RE.match(self.s, self.i)
            self.i = m.end()
            t = m.group(0)
            return float(t) if "." in t else int(t)
        word = self.ident()
        consts = {"true": True, "false": False, "null": None, "undefined": None}
        if word in consts:
            return consts[word]
        self.error("قيمة مش مفهومة: " + word)

    def ident(self):
        m = self.ID_RE.match(self.s, self.i)
        if not m:
            self.error("متوقع اسم")
        self.i = m.end()
        return m.group(0)

    def array(self):
        self.i += 1
        out = []
        while True:
            if self.peek() == "]":
                self.i += 1
                return out
            out.append(self.value())
            c = self.peek()
            if c == ",":
                self.i += 1
            elif c != "]":
                self.error("متوقع , أو ]")

    def obj(self):
        self.i += 1
        out = {}
        while True:
            c = self.peek()
            if c == "}":
                self.i += 1
                return out
            key = self.string() if c in "\"'" else self.ident()
            if self.peek() != ":":
                self.error("متوقع :")
            self.i += 1
            out[key] = self.value()
            c = self.peek()
            if c == ",":
                self.i += 1
            elif c != "}":
                self.error("متوقع , أو }")

    def string(self):
        q = self.s[self.i]
        self.i += 1
        buf = []
        esc = {"n": "\n", "t": "\t", "r": "", "b": "", "f": "", "0": ""}
        while self.i < self.n:
            c = self.s[self.i]
            if c == "\\":
                nx = self.s[self.i + 1]
                if nx == "u":
                    buf.append(chr(int(self.s[self.i + 2:self.i + 6], 16)))
                    self.i += 6
                    continue
                buf.append(esc.get(nx, nx))
                self.i += 2
            elif c == q:
                self.i += 1
                return "".join(buf)
            else:
                buf.append(c)
                self.i += 1
        self.error("نص مش مقفول")


