class Thinker:
    def __init__(self, kb, emb, net):
        self.kb, self.emb, self.net = kb, emb, net
        self.reader = Reader(kb, emb)
        self.deep = DeepThinker(kb, self.reader)  # العقل التاني

    def lesson_evidence(self, point, lesson):
        """بيدوّر في الدرس على الجملة اللي بتشرح الفكرة الناقصة"""
        pt = content_tokens(point)
        best, bs = None, 0.0
        for lid, s, toks in self.kb.sentences:
            if lid != lesson or toks == pt:  # بندوّر في شرح الدرس، مش في نص الفكرة نفسها
                continue
            cl = [c.strip(" «»") for c in re.split(r"[،,:]", s) if c.strip()]
            for i in range(len(cl)):  # جزء أو جزئين متتاليين من الجملة
                for part in (cl[i], "، ".join(cl[i:i + 2])):
                    ct = content_tokens(part)
                    if len(ct) < 2 or (len(pt) <= 3 and len(ct) < len(pt) + 2):  # الفكرة القصيرة محتاجة استشهاد فيه شرح
                        continue
                    sc = self.reader.soft_recall(pt, ct) - 0.015 * len(ct)
                    if sc > bs:
                        best, bs = part, sc
        return best if bs > 0.45 else None

    @staticmethod
    def short(s, n=90):
        s = re.sub(r"\s+", " ", s).strip()
        return s if len(s) <= n else s[:n].rsplit(" ", 1)[0] + "..."

    def grade_essay(self, q, answer):
        marks = float(q.get("marks", 4))
        lesson = self.kb.lessons.get(q.get("lesson"), {})
        answer = str(answer or "").strip()[:4000]
        th = []
        res = {"marks": marks, "score": 0.0, "ratio": 0.0, "confidence": "عالية", "found": [], "partial": [], "missing": [],
               "thoughts": th, "feedback": "", "model": q.get("model", "")}
        n_words = len(words(answer))
        th.append("قريت الإجابة: %s كلمة." % to_ar(n_words))
        nq = normalize(answer)
        cat_right = any(len(mc) == 1 and mc <= claimed_categories(answer, cs)
                        for cs in self.kb.cat_sets for mc in [claimed_categories(q.get("model", ""), cs)])
        if (len(content_tokens(answer)) < 2 and not cat_right) or any(nq == d or (nq.startswith(d) and n_words <= 5) for d in DONT_KNOW):
            th.append("الإجابة فاضية أو مفيهاش معلومات، فمفيش حاجة تتصحح.")
            res["missing"] = list(q.get("points", []))
            res["feedback"] = "مكتبتش إجابة. راجع الإجابة النموذجية تحت وحاول تكتبها بأسلوبك."
            return res
        f, info = self.reader.features(q, answer)
        pts = info["points"]
        th.append("السؤال من درس «%s»، ومطلوب فيه %s أفكار أساسية." % (lesson.get("title", ""), to_ar(len(pts))))
        flagged, flag_pts = [], []
        for (sc, where, flag), p in zip(info["pscores"], pts):
            if flag:
                flagged.append(flag)
                flag_pts.append(p)
                res["missing"].append(p)
                th.append(("فكرة «%s»: اتذكرت بس منفية في كلامك: «%s» — فمش هتتحسب." if flag == "neg" else
                           "فكرة «%s»: كلامك بيقول عكسها: «%s» — فمش هتتحسب.") % (p, self.short(where)))
            elif sc >= Reader.FOUND:
                res["found"].append(p)
                th.append("فكرة «%s»: موجودة في كلامك: «%s»" % (p, self.short(where)))
            elif sc >= 0.3 and where:
                res["partial"].append(p)
                th.append("فكرة «%s»: موجودة جزئيًا في كلامك: «%s» — بس ناقصها تفاصيل." % (p, self.short(where)))
            else:
                res["missing"].append(p)
                ev = self.lesson_evidence(p, q.get("lesson"))
                th.append("فكرة «%s»: ناقصة.%s" % (p, (" الدرس بيقول: «%s»" % self.short(ev)) if ev else ""))
        # ---- العقل التاني: فهم السؤال، قراءة تانية، واستجواب الأفكار ----
        qa = self.deep.analyze_question(q)
        self.deep.hedging(answer, th)
        self.deep.second_reading(q, answer, res, flag_pts, info, th, flagged)
        for _ in range(self.deep.polarity_review(answer, res, th)):
            flagged.append("flip")
        before = len(res["found"]) + 0.5 * len(res["partial"])
        deep_notes = []
        deep_notes += self.deep.check_echo(q, answer, res, th)
        deep_notes += self.deep.check_self_consistency(answer, res, th)
        deep_notes += self.deep.check_binding(q, answer, res, th, qa)
        deep_notes += self.deep.check_causality(q, answer, res, th)
        deep_notes += self.deep.check_numbers(res, info, th)
        downgraded = (len(res["found"]) + 0.5 * len(res["partial"])) < before
        tips = self.deep.check_requirements(qa, answer, res, th)
        pad_cap = self.deep.check_padding(q, answer, info, res, th)
        p_nn = self.net.predict(f)
        frac = (len(res["found"]) + 0.5 * len(res["partial"])) / len(pts)  # الفكرة الناقصة جزئيًا بنص درجة
        ratio = max(0.55 * p_nn + 0.45 * frac, frac - 0.05)  # لو كل الأفكار موجودة الدرجة بتقرب من النهائية
        caps = []
        if info["novelty"] < 0.3:
            caps.append((0.05, "أغلب الإجابة منقولة من نص السؤال نفسه."))
        if info["uniq"] < 0.4 and len(info["tokens"]) >= 5:
            caps.append((0.15, "في كلام متكرر كتير في الإجابة."))
        if info["known"] < 0.15 or (info["known"] < 0.35 and max(sc for sc, _, _ in info["pscores"]) < 0.3):
            caps.append((0.1, "أغلب الكلمات مش من المنهج أو مش مفهومة."))
        if f[5] < 0.35 and f[0] < 0.3:
            caps.append((0.15, "الإجابة بعيدة عن موضوع الدرس."))
        # رص كلمات: كلمات ورا بعض من غير أي أداة ربط، أو قايمة كل بند فيها كلمة واحدة
        items = [x for x in re.split(r"[.!؟?؛;،,:\n\-–/]+", answer) if words(x)]
        ws_all = words(answer)
        glue = sum(1 for w in ws_all if w in STOPWORDS or w in NEGATIONS or (w.startswith("و") and len(w) >= 3))
        if (len(items) == 1 and len(ws_all) >= 4 and glue == 0) or (len(items) >= 4 and all(len(words(x)) == 1 for x in items)):
            caps.append((0.25, "الإجابة كلمات مرصوصة من غير شرح."))
        # أسئلة الاختيار الواحد (الزاوية / نوع الخطاب / النمط)
        for cs in self.kb.cat_sets:
            mc = claimed_categories(q.get("model", ""), cs)
            if len(mc) != 1:
                continue
            right = next(iter(mc))
            ac = claimed_categories(answer, cs)
            names = [cs["cats"][i]["name"] for i in sorted(ac - mc)]
            if ac and right not in ac:
                res["cat"] = "wrong"
                th.append("السؤال مطلوب فيه اختيار واحد من «%s»، والإجابة اختارت: %s — وده مش الاختيار الصح." % (cs["title"], "، ".join(names)))
                caps.append((0.1, "اخترت «%s»، والإجابة الصح اختيار تاني من «%s»." % ("، ".join(names), cs["title"])))
            elif right in ac and len(ac) > 1:
                res["cat"] = "hedge"
                th.append("الإجابة ذكرت الاختيار الصح ومعاه اختيارات تانية (%s) — والسؤال مطلوب فيه اختيار واحد بس." % "، ".join(names))
                caps.append((0.25, "ذكرت أكتر من اختيار («%s» مع الصح)، والمطلوب اختيار واحد بس." % "، ".join(names)))
            elif right in ac:
                th.append("الاختيار صح: «%s»." % cs["cats"][right]["name"])
        # نسخ القطعة كلها بدل الإجابة
        if q.get("passage"):
            pt = set(content_tokens(q["passage"]))
            at = info["tokens"]
            if len(at) >= 8 and pt and sum(1 for t in at if t in pt) / len(at) >= 0.9 and len(set(at) & pt) >= 0.5 * len(pt):
                caps.append((0.1, "الإجابة منقولة من القطعة نفسها من غير شرح."))
        if pad_cap:
            caps.append(pad_cap)
        for cap, why in caps:
            th.append("انتباه: " + why)
            ratio = min(ratio, cap)
        ratio, conf_down = self.deep.deliberate(ratio, frac, p_nn, f, caps, res, th, downgraded)
        th.append("مدى ارتباط الإجابة بالدرس: %s٪ — والقرب في المعنى من الإجابة النموذجية: %s٪."
                  % (to_ar(round(f[5] * 100)), to_ar(round(f[4] * 100))))
        agree = 1 - abs(p_nn - frac)
        conf = "عالية" if agree >= 0.75 or p_nn < 0.15 or p_nn > 0.85 else ("متوسطة" if agree >= 0.5 else "منخفضة")
        if conf_down:
            conf = {"عالية": "متوسطة", "متوسطة": "منخفضة"}.get(conf, conf)
        th.append("الشبكة العصبية قدّرت جودة الإجابة بـ %s٪ (الثقة: %s)." % (to_ar(round(p_nn * 100)), conf))
        if frac == 0 and not caps:
            th.append("مفيش ولا فكرة من الأفكار المطلوبة في الإجابة.")
            ratio = 0.0
        ratio = max(0.0, min(1.0, ratio))
        score = (math.floor if caps else round)(ratio * marks * 2) / 2
        th.append(self.deep.conclusion(res, marks, score))
        th.append("الدرجة النهائية: %s من %s." % (to_ar(score), to_ar(marks)))
        # هل الدرجة دي محتاجة عين المعلم؟
        review = ""
        if flagged:
            review = "المصحح لقى في إجابتك نفي أو عكس لفكرة من الأفكار المطلوبة فمحسبهاش. لو قصدك كان غير كده، اعرض إجابتك على المعلم."
        elif not caps and n_words >= 12 and ratio <= 0.4 and info["topic"] >= 0.35 and info["known"] >= 0.15:
            review = "إجابتك طويلة ومتعلقة بالدرس، بس مكتوبة بكلمات بعيدة عن الإجابة النموذجية، فالمصحح مش متأكد من درجتها. الدرجة دي مبدئية، واعرضها على المعلم يراجعها."
        elif conf == "منخفضة":
            review = "ثقة المصحح في الدرجة دي منخفضة، فالأحسن المعلم يراجعها."
        if review:
            th.append("قرار: الإجابة دي محتاجة مراجعة المعلم.")
        res.update(score=score, ratio=round(ratio, 3), confidence=conf, nn=round(p_nn, 3), review=review)
        if score >= marks:
            res["feedback"] = "ممتاز! إجابتك فيها كل الأفكار المطلوبة."
        elif (res["found"] or res["partial"]) and not caps:
            res["feedback"] = ("إجابة كويسة، بس ناقصها: " if res["found"] else "بدأت صح، بس ناقصك: ") + "، ".join(res["partial"] + res["missing"]) + "."
        elif caps:
            res["feedback"] = caps[0][1] + " اكتب الأفكار المطلوبة بأسلوبك."
        elif flagged:
            res["feedback"] = "إجابتك ذكرت الأفكار بس نفتها أو قالت عكسها. راجع الجزء ده في الدرس."
        else:
            res["feedback"] = "الإجابة مش فيها الأفكار المطلوبة. راجع الجزء ده في الدرس."
        if score < marks and deep_notes:  # ملاحظة الاستجواب أهم حاجة يعرفها الطالب
            res["feedback"] = deep_notes[0] + " " + res["feedback"]
        if score < marks and tips:
            res["feedback"] += " " + tips[0]
        return res

    # ---- الأسئلة الموضوعية ----
    @staticmethod
    def grade_objective(q, value):
        t = q.get("type")
        marks = MARKS.get(t, 1)
        out = {"marks": marks, "score": 0.0, "given": "لم تُجب", "correct_text": ""}
        if t == "mcq":
            out["correct_text"] = q["options"][q["answer"]]
            if isinstance(value, int) and 0 <= value < len(q["options"]):
                out["given"] = q["options"][value]
                out["score"] = float(marks) if value == q["answer"] else 0.0
        elif t == "tf":
            out["correct_text"] = "صح" if q["answer"] else "خطأ"
            if isinstance(value, bool):
                out["given"] = "صح" if value else "خطأ"
                out["score"] = float(marks) if value == bool(q["answer"]) else 0.0
        elif t == "fill":
            ans = q["answer"] if isinstance(q["answer"], list) else [q["answer"]]
            out["correct_text"] = ans[0]
            if isinstance(value, str) and value.strip():
                out["given"] = value
                out["score"] = float(marks) if normalize(value) in [normalize(a) for a in ans] else 0.0
        elif t == "match":
            pairs = q["pairs"]
            out["correct_text"] = " ، ".join("%s: %s" % (p["a"], p["b"]) for p in pairs)
            if isinstance(value, dict) and value:
                good, given = 0, []
                for i, p in enumerate(pairs):
                    v = value.get(str(i))
                    try:
                        j = int(v)
                    except (TypeError, ValueError):
                        j = -1
                    good += 1 if j == i else 0
                    given.append("%s: %s" % (p["a"], pairs[j]["b"] if 0 <= j < len(pairs) else "—"))
                out["given"] = " ، ".join(given)
                out["score"] = round(good / len(pairs) * marks * 2) / 2
                out["pairs_ok"] = good
        return out

    # ---- «تحقق من إجابتك» في التطبيق العملي ----
    def classify_check(self, t, text):
        """تطبيقات التصنيف (زي: صنّف كل وسيلة عقلية أم عاطفية): الإجابة النموذجية سطور «أ: ب».
        المصحح بيعرف من الإجابة النموذجية كل عنصر تبع أنهي تصنيف، وبيقرا إجابة الطالب بالترتيب:
        لو بدأ بالتصنيف («عقلية: الإحصائيات...») العنصر بياخد التصنيف اللي قبله،
        ولو بدأ بالعنصر («الإحصائيات عقلية...») العنصر بياخد التصنيف اللي بعده.
        بيرجّع None لو التطبيق مش تصنيف، أو (العناصر اللي اتصنفت غلط، العناصر اللي ماتصنفتش)."""
        kws = [(kw, set(content_tokens(kw))) for kw in t.get("check", [])]
        kws = [(kw, ks) for kw, ks in kws if ks]
        lines = [ln.strip().rstrip(".") for ln in t.get("model", "").split("\n") if ln.strip()]
        if len(kws) < 2 or len(lines) < 2 or not all(":" in ln for ln in lines):
            return None
        rows = []
        for ln in lines:
            left, right = ln.split(":", 1)
            lt, rt = set(content_tokens(left)), set(content_tokens(right))
            in_l = [kw for kw, ks in kws if ks <= lt]
            in_r = [kw for kw, ks in kws if ks <= rt]
            rows.append((left, right, in_l, in_r))
        if all(len(r[2]) == 1 and not r[3] for r in rows):
            pairs = [(it, r[2][0]) for r in rows for it in r[1].split("،")]
        elif all(len(r[3]) == 1 and not r[2] for r in rows):
            pairs = [(r[0], r[3][0]) for r in rows]
        else:
            return None
        if {c for _, c in pairs} != {kw for kw, _ in kws}:
            return None
        cat_of_tok = {}
        for kw, ks in kws:
            for x in ks:
                cat_of_tok[x] = kw
        items = [(re.sub(r"^و(?=ال)", "", it.strip()), [x for x in content_tokens(it) if x not in cat_of_tok], c) for it, c in pairs]
        items = [(it, tk, c) for it, tk, c in items if tk]
        if len(items) < 2 or any(len(tk) > 4 for _, tk, _ in items):
            return None
        count = Counter(x for _, tk, _ in items for x in set(tk))
        item_of_tok, right_cat = {}, {}
        for it, tk, c in items:
            own = [x for x in tk if count[x] == 1]
            if not own:
                return None
            right_cat[it] = c
            for x in own:
                item_of_tok[x] = it
        events = []
        for x in content_tokens(text):
            if x in cat_of_tok:
                events.append(("c", cat_of_tok[x]))
            elif x in item_of_tok and not (events and events[-1] == ("i", item_of_tok[x])):
                events.append(("i", item_of_tok[x]))
        given = {}
        cat_first = bool(events) and events[0][0] == "c"
        for k, (kind, val) in enumerate(events):
            if kind != "i":
                continue
            rng = range(k - 1, -1, -1) if cat_first else range(k + 1, len(events))
            c = next((events[j][1] for j in rng if events[j][0] == "c"), None)
            if c:
                given.setdefault(val, set()).add(c)
        wrong = [it for it in right_cat if it in given and given[it] != {right_cat[it]}]
        missing = [it for it in right_cat if it not in given]
        return wrong, missing

    def check_task(self, lesson_id, part_i, text):
        L = self.kb.lessons.get(lesson_id)
        if not L:
            return {"error": "الدرس مش موجود"}
        parts = L["raw"].get("parts", [])
        if not (0 <= part_i < len(parts)) or not parts[part_i].get("task"):
            return {"error": "الجزء ده مفيهوش تطبيق"}
        t = parts[part_i]["task"]
        # في تطبيقات التصنيف الإجابة لازم تستخدم كلمات الخطوات نفسها (الإحصائيات، الصور البيانية...)،
        # فالنقل هنا معناه لصق الخطوات كلها، مش استخدام كلماتها — عشان كده بنقيسه لوحده
        steps_toks = set(content_tokens(" ".join(t.get("steps", []))))
        q = {"q": "", "model": t.get("model", ""), "points": split_points(t.get("model", ""), 1),
             "lesson": lesson_id, "marks": 1}
        ans_list = content_tokens(text)
        pasted = False
        if steps_toks and ans_list:
            cover = len(steps_toks & set(ans_list)) / len(steps_toks)
            fresh = sum(1 for x in ans_list if x not in steps_toks) / len(ans_list)
            pasted = cover >= 0.6 and fresh < 0.3
        toks = set(ans_list)
        missing_kw = []
        for kw in t.get("check", []):  # الكلمات الأساسية لازم تكون موجودة (حتى لو مكتوبة من غير همزة أو تشكيل)
            kt = content_tokens(kw)
            if not kt or self.reader.soft_recall(kt, list(toks), toks) < 0.75:
                missing_kw.append(kw)
        g = self.grade_essay(q, text)
        cls = None if pasted else self.classify_check(t, text)
        if cls and (cls[0] or cls[1]):
            wrong, miss = cls
            if wrong:
                g["thoughts"].append("تصنيف غلط: " + "، ".join(wrong))
                g["feedback"] = "راجع تصنيف: " + "، ".join(wrong) + " — كل عنصر ليه تصنيف واحد صح."
            else:
                g["thoughts"].append("عناصر ماتصنفتش: " + "، ".join(miss))
                g["feedback"] = "لسه ماصنفتش: " + "، ".join(miss) + " — اكتب كل عنصر وجنبه تصنيفه."
        bad_cls = bool(cls and (cls[0] or cls[1])) or bool(g.get("bound_wrong")) or bool(g.get("causal_flip"))
        junk = pasted or any(("منقولة" in x or "متكرر" in x or "مش مفهومة" in x) for x in g["thoughts"])
        if pasted:
            g["thoughts"].append("انتباه: الإجابة منسوخة من خطوات التطبيق نفسها.")
            g["feedback"] = "إنت نسخت خطوات التطبيق زي ما هي — اكتب إجابتك إنت بعد ما تحل المطلوب."
        bad_cat = g.get("cat") in ("wrong", "hedge")  # اختيار غلط أو أكتر من اختيار
        ok = bool(text.strip()) and not missing_kw and not junk and not bad_cat and not bad_cls and g["ratio"] >= 0.2
        return {"ok": ok, "missing": missing_kw, "extra": [] if ok else g["missing"][:3], "ratio": g["ratio"],
                "thoughts": g["thoughts"], "feedback": ("لقد فعلتها! إجابتك فيها كل المطلوب." if ok else
                                                         ("لسه ناقص: " + "، ".join(missing_kw) if missing_kw and not bad_cat and not pasted and not bad_cls else g["feedback"]))}


