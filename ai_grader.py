def normalize(text):
    """بيشيل التشكيل والتطويل ويوحّد (أ إ آ ← ا) و(ة ← ه) و(ى ← ي) والأرقام"""
    t = DIAC_RE.sub("", str(text or ""))
    t = re.sub("[أإآٱ]", "ا", t)
    t = t.replace("ة", "ه").replace("ى", "ي").replace("ؤ", "و").replace("ئ", "ي")
    t = t.translate(DIGIT_MAP)
    t = PUNCT_RE.sub(" ", t)
    return re.sub(r"\s+", " ", t).strip().lower()


