def colloquial_to_msa(text, vocab=None):
    """بيحوّل كلام الطالب العامي لفصحى كلمة بكلمة (وجمل صغيرة زي «عشان كده» ← «لذلك»)
    الفعل العامي («بيحموا») بيتحوّل بس لو الكلمة من غير «ب» موجودة في المنهج — عشان «بيئة» و«هيئة» ماتتلخبطش"""
    ws = words(text)
    out, i = [], 0
    while i < len(ws):
        hit = None
        for n in (4, 3, 2):
            key = tuple(ws[i:i + n])
            if len(key) == n and key in _EGY_P:
                hit = (_EGY_P[key], n)
                break
            if len(key) == n and key[0][:1] in "وف" and (key[0][1:],) + key[1:] in _EGY_P:  # «ومحدش يقدر»
                hit = (key[0][0] + _EGY_P[(key[0][1:],) + key[1:]], n)
                break
        if hit:
            out.append(hit[0])
            i += hit[1]
            continue
        w = ws[i]
        pre = ""
        if len(w) >= 4 and w[0] in "وف" and w[1:] in _EGY_W:  # «وعشان» ← و + لأن
            pre, w = w[0], w[1:]
        if w in _EGY_W:
            out.append(pre + _EGY_W[w] if " " not in _EGY_W[w] else _EGY_W[w])
        elif vocab is not None and len(w) >= 5 and w.startswith(EGY_VERB_PREFIX) \
                and stem(w) not in vocab and stem(w[1:]) in vocab:  # فعل مضارع بالعامية ← فصحى
            out.append(pre + w[1:])
        else:
            out.append(pre + w)
        i += 1
    return " ".join(out)


