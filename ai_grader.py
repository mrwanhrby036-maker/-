def find_causal(ws):
    """أول رابط سبب ونتيجة في الجملة: (مكانه، طوله، اتجاهه)"""
    for i in range(len(ws)):
        for seq, d in CAUSAL_LINKS:
            if tuple(ws[i:i + len(seq)]) == seq:
                return i, len(seq), d
    return None


def split_cause_effect(text):
    """الجملة ← (كلمات السبب، كلمات النتيجة) لو فيها رابط سببي"""
    ws = words(text)
    hit = find_causal(ws)
    if not hit:
        return None
    i, n, d = hit
    left = [stem(w) for w in ws[:i] if w not in STOPWORDS and not is_neg(w) and len(w) > 1]
    right = [stem(w) for w in ws[i + n:] if w not in STOPWORDS and not is_neg(w) and len(w) > 1]
    if len(left) < 2 or len(right) < 2:
        return None
    return (left, right) if d == 1 else (right, left)


