CONFUSABLE = set()
for _pair in ("ثس", "ثت", "ذز", "ذد", "ظض", "ظز", "ضد", "صس", "طت", "قا", "حه", "عا", "كق", "زس", "ءي", "ءا", "ءو"):
    CONFUSABLE.add((_pair[0], _pair[1]))
    CONFUSABLE.add((_pair[1], _pair[0]))


def sub_cost(a, b):
    if a == b:
        return 0.0
    return 0.5 if (a, b) in CONFUSABLE else 1.0


def weighted_edit(a, b, limit=2.0):
    """مسافة التعديل بين كلمتين (حذف / إضافة / تبديل / قلب حرفين جنب بعض) بأوزان عربية"""
    if abs(len(a) - len(b)) > limit:
        return limit + 1
    prev2 = None
    prev = [float(j) for j in range(len(b) + 1)]
    for i in range(1, len(a) + 1):
        cur = [float(i)] + [0.0] * len(b)
        row_min = cur[0]
        for j in range(1, len(b) + 1):
            c = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + sub_cost(a[i - 1], b[j - 1]))
            if prev2 is not None and i > 1 and j > 1 and a[i - 1] == b[j - 2] and a[i - 2] == b[j - 1]:
                c = min(c, prev2[j - 2] + 0.5)  # حرفين اتقلبوا: «الحضراة» ← «الحضارة»
            cur[j] = c
            row_min = min(row_min, c)
        if row_min > limit:
            return limit + 1
        prev2, prev = prev, cur
    return prev[-1]


class SpellFixer:
    def __init__(self, kb):
        self.kb = kb
        self.cache = {}

    def fix(self, tok):
        """لو الكلمة مش في المنهج: أقرب كلمة من المنهج ليها (بشرط تكون واضحة ومفيش كلمتين بنفس القرب)"""
        if tok in self.kb.vocab or len(tok) < 4 or tok.isdigit():
            return tok
        if tok in self.cache:
            return self.cache[tok]
        limit = 0.5 if len(tok) <= 5 else (1.0 if len(tok) <= 7 else 1.5)  # الكلمة القصيرة: لخبطة حرف متشابه بس
        best, bd, tie = tok, limit + 0.01, False
        cands = set()
        for g in grams(tok):  # المرشحين: كلمات المنهج اللي بتشارك الكلمة في ٣ حروف ورا بعض على الأقل
            cands |= self.kb.gram_index.get(g, set())
        for c in sorted(cands):
            if abs(len(c) - len(tok)) > 1 or c.isdigit():
                continue
            if c[0] != tok[0] and (c[0], tok[0]) not in CONFUSABLE and c[-1] != tok[-1]:
                continue  # كلمتين مختلفين في أولهم وآخرهم: مش غلطة إملائية
            d = weighted_edit(tok, c, limit)
            if d < bd:
                best, bd, tie = c, d, False
            elif d == bd and c != best:
                tie = True
        out = tok if tie else best
        self.cache[tok] = out
        return out


