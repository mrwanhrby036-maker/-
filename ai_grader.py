CAT_FILLERS = _n("وايضا ايضا كمان وكمان برضه وبرضه ربما يمكن يحتمل وممكن ممكن وكذلك كذلك")  # كلام حشو بين الاختيارات
HEAD_STEMS = set()  # الكلمات اللي بتيجي قبل الاختيار: «زاوية علمية» «الخطاب السردي» «نمط ...»


def _heads():
    if not HEAD_STEMS:
        HEAD_STEMS.update(stem(w) for w in words("زاوية الزاوية زوايا خطاب الخطاب نمط النمط نوع انتقال الانتقال منظور المنظور"))
    return HEAD_STEMS


def category_alternates(cell):
    """صيغ الاختيار من خانة الجدول: «زاوية وجدانية (عاطفية)» ← (وجدان) أو (عاطف)
    «من العام إلى الخاص» ← (عام، خاص) بالترتيب — عشان متتلخبطش مع «من الخاص إلى العام»"""
    heads = _heads()
    inner = re.findall(r"\(([^)]*)\)", cell)
    main = re.sub(r"\([^)]*\)", " ", cell)
    alts = []
    for ch in re.split(r"\s+أو\s+", main) + inner:
        ws = [w for w in words(ch) if w not in STOPWORDS]
        ws = [w for w in ws if stem(w) not in heads]
        toks = tuple(stem(w) for w in ws)
        if not toks:
            continue
        alts.append(toks)
        # صفتين ورا بعض («فلسفية فكرية»، «الإخباري التقريري»): كل صفة لوحدها تكفي
        if len(toks) == 2 and not any(w.startswith("و") for w in ws[1:]):
            for w, t in zip(ws, toks):
                if (w.endswith("ي") or w.endswith("يه")) and len(t) >= 4:
                    alts.append((t,))
    out = []
    for a in alts:
        if a not in out:
            out.append(a)
    return out


def claimed_categories(text, cset):
    """الاختيارات اللي الكلام «بيقرر» إنها الإجابة: بعد «زاوية/الخطاب/نمط»، أو في أول الإجابة،
    أو معطوفة على اختيار تاني («علمية واقتصادية» / «علمية أو تاريخية») — ومش منفية («وليست اقتصادية»)"""
    heads = _heads()
    ws = words(text)
    seq = [(stem(w), i) for i, w in enumerate(ws) if w not in STOPWORDS and w not in CAT_FILLERS]
    stems = [x for x, _ in seq]
    ments = []
    for ci, c in enumerate(cset["cats"]):
        for alt in c["alts"]:
            n = len(alt)
            for k in range(len(seq) - n + 1):
                if tuple(stems[k:k + n]) == alt:
                    ments.append((k, -n, ci))
    ments.sort()
    claimed, ends, taken = set(), set(), set()
    for k, negn, ci in ments:
        n = -negn
        if any(j in taken for j in range(k, k + n)):
            continue  # جزء من اختيار أطول اتحسب خلاص
        i0 = seq[k][1]
        if any(is_neg(w) for w in ws[max(0, i0 - 2):i0]):
            continue
        if k == 0 or stems[k - 1] in heads or k in ends:
            claimed.add(ci)
            ends.add(k + n)
            taken.update(range(k, k + n))
    return claimed


def sigmoid(x):
    if x < -30:
        return 0.0
    if x > 30:
        return 1.0
    return 1.0 / (1.0 + math.exp(-x))


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def cosine(a, b):
    na, nb = math.sqrt(dot(a, a)), math.sqrt(dot(b, b))
    return dot(a, b) / (na * nb) if na and nb else 0.0


class WordEmbeddings:
    def __init__(self, dim=16):
        self.dim, self.vec, self._oov = dim, {}, {}

    def train(self, sentences, rng, epochs=4, window=2, neg=3, lr=0.05):
        vocab = sorted({t for s in sentences for t in s})
        idx = {w: i for i, w in enumerate(vocab)}
        freq = [0] * len(vocab)
        for s in sentences:
            for t in s:
                freq[idx[t]] += 1
        table = []
        for i, f in enumerate(freq):
            table += [i] * max(1, int(round(f ** 0.75)))
        W = [[(rng.random() - 0.5) / self.dim for _ in range(self.dim)] for _ in vocab]
        C = [[0.0] * self.dim for _ in vocab]
        total, step = epochs * len(sentences), 0
        for ep in range(epochs):
            order = list(range(len(sentences)))
            rng.shuffle(order)
            for si in order:
                s = [idx[t] for t in sentences[si]]
                a = lr * max(0.1, 1 - step / total)
                step += 1
                for i, center in enumerate(s):
                    wc = W[center]
                    for j in range(max(0, i - window), min(len(s), i + window + 1)):
                        if j == i:
                            continue
                        grad = [0.0] * self.dim
                        targets = [(s[j], 1.0)] + [(table[rng.randrange(len(table))], 0.0) for _ in range(neg)]
                        for tgt, label in targets:
                            ct = C[tgt]
                            g = a * (label - sigmoid(dot(wc, ct)))
                            for k in range(self.dim):
                                grad[k] += g * ct[k]
                                ct[k] += g * wc[k]
                        for k in range(self.dim):
                            wc[k] += grad[k]
        self.vec = {w: W[i] for i, w in enumerate(vocab)}

    def get(self, tok, kb=None):
        v = self.vec.get(tok)
        if v is not None:
            return v
        if tok in self._oov:
            return self._oov[tok]
        v = None
        if kb is not None:  # كلمة جديدة؟ ناخد معنى أقرب كلمة ليها في الحروف
            near, _ = kb.nearest_word(tok)
            v = self.vec.get(near) if near else None
        self._oov[tok] = v
        return v

    def sentence(self, toks, kb):
        acc, tw = [0.0] * self.dim, 0.0
        for t in toks:
            v = self.get(t, kb)
            if v is None:
                continue
            w = kb.w(t)
            nv = math.sqrt(dot(v, v)) or 1.0
            for k in range(self.dim):
                acc[k] += w * v[k] / nv
            tw += w
        return [x / tw for x in acc] if tw else acc

    def neighbours(self, tok, k=3):
        v = self.vec.get(tok)
        if v is None:
            return []
        sims = sorted(((cosine(v, u), w) for w, u in self.vec.items() if w != tok), reverse=True)
        return [w for s, w in sims[:k] if s > 0.6]


